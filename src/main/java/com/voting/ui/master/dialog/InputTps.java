    private void loadTps(Tps t){
        // <editor-fold defaultstate="collapsed" desc="Compiled Code">
        cKab.setEnabled(true);cKec.setEnabled(true);cDes.setEnabled(true);
        List<Kab> kab = ms.getFromProv(t.getProvCode());
        List<Kec> kec = ms.getFromKab(t.getKabCode());
        List<Des> des = ms.getFromKec(t.getKecCode());
        cKab.setModel(new DefaultComboBoxModel<Kab>(kab.toArray(new Kab[0])));
        cKec.setModel(new DefaultComboBoxModel<Kec>(kec.toArray(new Kec[0])));
        cDes.setModel(new DefaultComboBoxModel<Des>(des.toArray(new Des[0])));
        cProv.setSelectedItem(t.getProvCode());cKab.setSelectedItem(t.getKabCode());
        cKec.setSelectedItem(t.getKecCode());cDes.setSelectedItem(t.getDesCode());
        fDesk.setText(t.getDesk());fNo.setText(t.getNo());fCode.setText(t.getCode());//</editor-fold>
    }
    private void tpsIsSet(){
        // <editor-fold defaultstate="collapsed" desc="Compiled Code">
        Object[] o= {cProv,cKab,cKec,cDes,fNo};
        for(Object t : o){
            if(t instanceof javax.swing.JComboBox){
                ((javax.swing.JComboBox) t).setEnabled(false);
            } else{
                ((javax.swing.JTextField) t).setEditable(false);
            }
        }// </editor-fold>
    }
    private String setCode(Object o){
        // <editor-fold defaultstate="collapsed" desc="Compiled Code">
        if(o instanceof Prov){
            return ((Prov) o).getCode();
        } else if(o instanceof Kab){
            return ((Kab) o).getCode();
        } else if(o instanceof Kec){
            return ((Kec) o).getCode();
        } else{
            return ((Des) o).getCode(); 
        }//</editor-fold>
    }
    private String setTpsCode(Des d, String no){
        // <editor-fold defaultstate="collapsed" desc="Compiled Code">
        if(no.length()==1){no=".0"+no;}else{no="."+no;}
        return d.getCode()+no+"";//</editor-fold>
    }
    private Tps setTps(){
        // <editor-fold defaultstate="collapsed" desc="Compiled Code">
        if(tps==null){
            Prov p=(Prov)cProv.getSelectedItem();Kab b=(Kab)cKab.getSelectedItem();
            Kec c=(Kec)cKec.getSelectedItem();Des d=(Des)cDes.getSelectedItem();
            String code=fCode.getText(), noo=fNo.getText(), desk=fDesk.getText();
            
            tps=new Tps(p,b,c,d,code,noo,desk);
        } else{
            tps.setDesk(fDesk.getText());
        }
        return tps;//</editor-fold>
    }
    private boolean isValidated(){
        if(fCode.getText().isEmpty()){
            JOptionPane.showMessageDialog(this,
                "TPS Belum Diatur","TPS Harus Diisi", JOptionPane.ERROR_MESSAGE);
            fNo.requestFocus();
            return false;
        }
        return true;
    }
