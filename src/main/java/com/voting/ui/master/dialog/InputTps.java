    private void kCode(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_kCode
        if(fNo.getText().length()<=2){
            no=fNo.getText();
            fCode.setText(setTpsCode((Des)cDes.getSelectedItem(),no));
        } else{
            JOptionPane.showMessageDialog(this,
                "Nomor TPS Tidak Boleh Lebih dari 99", "Melebihi Jumlah Maksimum", JOptionPane.ERROR_MESSAGE);
            fNo.setText(no);fNo.requestFocus();
        }
    }//GEN-LAST:event_kCode

    private void eSave(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_eSave
        if(isValidated()){           
            if(tps==null){
                if(ms.getTps(fCode.getText())!=null){
                    JOptionPane.showMessageDialog(this,
                            "TPS Sudah Terdaftar", "Data Sudah Ada", JOptionPane.ERROR_MESSAGE);                    
                } else{
                    ms.saveTps(setTps());
                    ss.makeLog(DataLogger.makeLog(setTps(), DataLogger.ADD));
                    dispose();
                }
            } else{
                ms.updateTPS(setTps());
                ss.makeLog(DataLogger.makeLog(setTps(), DataLogger.EDIT));
                dispose();
            }
        }
    }//GEN-LAST:event_eSave

